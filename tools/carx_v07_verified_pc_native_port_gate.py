#!/usr/bin/env python3
"""CarX Street Android-native PC-port engineering decision from an OWNED report.

This program does not contain or upload the user's private game files,
execute a Windows binary, decode metadata, or forge an Android port.

Input: CarX_Street_PC_Port_Report_v0.7.json generated by our Android SAF
      inspector on the owner's phone. The complete source report is kept
      local by default. Output is a minimized, redacted decisions-only JSON.

No native-Android gameplay claim can be inferred from:
  - Vulkan device test, no matter how successful,
  - a count of assets or catalog references,
  - 'Android' being present as a substring in one catalog ID,
  - an x86_64 PE DLL's import table,
  - zero static Steam/EAC imports (dynamic imports remain unknown).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

SCHEMA = "rm11carx.v0.7.native-android-game-g0-g1-g2-gate.v1"
MAX_REPORT_BYTES = 2_000_000
FORBIDDEN_DIRECT_LOAD_PREFIX = "Windows-PE-"

class ValidationError(ValueError):
    pass


def expect(condition: bool, message: str) -> None:
    if not condition:
        raise ValidationError(message)


def mapping(v: Any, name: str) -> dict[str, Any]:
    expect(isinstance(v, dict), f"{name} must be an object")
    return v


def integer(v: Any, name: str, upper: int = 2_000_000) -> int:
    expect(type(v) is int and 0 <= v <= upper, f"{name} is not a bounded nonnegative integer")
    return v


def source_imports(obj: Any, key: str) -> dict[str, Any]:
    node = mapping(obj, key)
    expect(node.get("present") is True, f"{key}: source binary not present")
    expect(node.get("pe_header_valid") is True, f"{key}: original PE header unverified")
    expect(node.get("pe_import_directory_complete") is True,
           f"{key}: original static import table incomplete")
    expect(node.get("saf_random_read_supported") is True,
           f"{key}: actual SAF source random-access read was not proven")
    dlls = node.get("static_import_library_names")
    expect(isinstance(dlls, list) and len(dlls) <= 256,
           f"{key}: invalid static import list")
    expect(all(isinstance(x, str) and 0 < len(x) <= 256 for x in dlls),
           f"{key}: invalid DLL names")
    return {
        "source_pe_machine": node.get("machine_architecture"),
        "source_format": node.get("source_binary_format"),
        "static_import_count": len(dlls),
        "windows_graphics_dlls_present": sorted(set(dlls) & {
            "d3d11.dll", "dxgi.dll", "d3d12.dll", "opengl32.dll",
        }),
        "windows_os_dlls_present": sorted(set(dlls) & {
            "kernel32.dll", "user32.dll", "ws2_32.dll",
            "advapi32.dll", "ole32.dll", "oleaut32.dll",
        }),
        "unity_baselib_dependency_detected": "baselib.dll" in dlls,
        "steam_eac_eos_static_imports_present": sorted(
            x for x in dlls
            if "steam" in x or "easyanticheat" in x or
               x.startswith("eac") or "eos" in x
        ),
        "static_import_absence_does_not_exclude_runtime_dynamic_loads": True,
        "android_elf_bionic_game_binary": False,
    }


def evaluate(report: dict[str, Any]) -> dict[str, Any]:
    expect(report.get("schema") == "rm11carx.pc-port-readonly-inspector.v1",
           "unknown source game report schema")
    expect(report.get("inspector_version") == "0.7.0",
           "not a CarX v0.7 source report")
    expect(report.get("source_game") == "CarX Street PC (Unity IL2CPP)",
           "wrong game")
    expect(report.get("read_only") is True and
           report.get("game_files_transmitted") is False,
           "original source sample privacy conditions unverified")

    count = mapping(report.get("counts"), "counts")
    expect(count.get("scan_incomplete") is False,
           "original source file census incomplete")
    files = integer(count.get("files"), "files")
    original = mapping(report.get("windows_source_dependency_probe"),
                       "windows_source_dependency_probe")
    expect(original.get("schema") ==
           "rm11carx.android-saf-windows-gamecode-asset-gate.v1",
           "source imports were not read via genuine Android SAF")
    expect(original.get("executes_windows_game_binaries") is False,
           "source scan did not assert no original game execution")
    deps = mapping(original.get("pc_executable_dependencies"),
                   "pc_executable_dependencies")
    game = source_imports(deps.get("game_assembly"), "game_assembly")
    player = source_imports(deps.get("unity_player"), "unity_player")

    catalog = mapping(original.get("addressables_platform_references"),
                      "addressables_platform_references")
    expect(catalog.get("present") is True and
           catalog.get("full_file_parsed") is True,
           "source Addressables catalog unavailable/incomplete")
    ids = integer(catalog.get("internal_id_count"), "internal_id_count",
                  100_000)
    ref_windows = integer(catalog.get("standalone_windows64_references"),
                          "standalone_windows64_references", 100_000)
    bundle_refs = integer(catalog.get("bundle_extension_references"),
                          "bundle_extension_references", 100_000)
    android_named = integer(catalog.get("android_named_references"),
                            "android_named_references", 100_000)
    actual_bundles = integer(mapping(report.get("unity_deep_probe"),
                   "unity_deep_probe").get("windows64_bundle_count"),
                   "windows64_bundle_count", 100_000)

    # Scope both counts correctly. One can be an extra loose/uncataloged
    # bundle; another can be URL placeholder, duplicated reference, or
    # generated runtime locator. Counts cannot prove missing files.
    difference = actual_bundles - bundle_refs
    need_android_asset_evidence = (
        catalog.get("android_target_bundle_shaders_compatible_proven") is True
        and catalog.get("original_pc_windows_bundle_conversion_proven") is True
    )
    expect(original.get("android_arm64_carx_game_logic_proven") is False,
           "unexpected game-execution claim requires independent evidence")
    native_gpu = mapping(report.get("native_arm64_vulkan_preflight"),
                         "native_arm64_vulkan_preflight")
    gpu_ok = native_gpu.get("native_gpu_work_verified") is True
    codes_are_pe_windows = (
        game["source_pe_machine"].startswith(FORBIDDEN_DIRECT_LOAD_PREFIX) and
        player["source_pe_machine"].startswith(FORBIDDEN_DIRECT_LOAD_PREFIX)
    ) if (isinstance(game["source_pe_machine"], str) and
          isinstance(player["source_pe_machine"], str)) else False
    # A non-PE or unrecognized architecture cannot be elevated to a native
    # Android port; it is merely a report requiring independent review.
    expect(codes_are_pe_windows, "original code machine architecture not confirmed Windows PE")
    unity = mapping(mapping(report["unity_deep_probe"],
                    "unity_deep_probe").get("unity_serialized_file_headers"),
                    "unity_serialized_file_headers")
    unity_versions = unity.get("candidate_unity_editor_versions")
    unity_version = unity_versions[0] if (isinstance(unity_versions, list) and
                                         len(unity_versions) == 1 and
                                         isinstance(unity_versions[0], str)) else "unverified"
    # Even a future report falsely toggling a flag cannot make the two
    # crucial independent executable/asset acceptance proofs appear.
    return {
        "schema": SCHEMA,
        "derived_from_actual_user_android_saf_v07_report": True,
        "privacy": {
            "report_device_identity_in_output": False,
            "whole_game_binary_bytes_in_output": False,
            "source_file_paths_in_output": False,
        },
        "source_game": "CarX Street PC",
        "unity_editor_version_candidate": unity_version,
        "source_files_count": files,
        "source_code": {"game_assembly": game, "unity_player": player},
        "addressables": {
            "internal_id_count": ids,
            "original_windows64_bundle_file_count": actual_bundles,
            "catalog_bundle_extension_reference_count": bundle_refs,
            "catalog_windows64_reference_count": ref_windows,
            "catalog_android_name_substring_count": android_named,
            "bundle_file_minus_catalog_reference_count": difference,
            "bundle_file_count_vs_catalog_count_is_missing_file_proof": False,
            "android_substring_is_android_asset_bundle_proof": False,
            "android_target_game_bundle_verified": need_android_asset_evidence,
            "catalog_dependency_closure_verified": False,
        },
        "hardware": {
            "original_independent_native_arm64_gpu_clear_and_readback_proven": gpu_ok,
            "gpu_success_means_original_game_runnable": False,
        },
        "native_port_acceptance": {
            "G0_authorized_original_android_arm64_gameplay_code_verified": False,
            "G1_original_android_platform_asset_bundle_verified": False,
            "G2_original_carx_game_scene_frame_and_controls_verified": False,
            "strict_no_emulation_playable_pc_port": False,
            "stage": "NO_GO_ORIGINAL_GAME_CODE_AND_ANDROID_ASSETS_ABSENT",
            "current_proven_result": "Original Windows binary static import and original Windows catalog header/dependency analysis complete",
        },
        "next_actual_dependency": (
            "Obtain legally usable CarX Street game source or a licensed "
            "native Android ARM64 IL2CPP game build AND Android platform "
            "assets; otherwise an independent clean-room reimplementation. "
            "Windows/Darwin compatibility layers or x86 translation in a "
            "game-specific APK are not a strict no-emulation native port."
        ),
    }


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("user_owned_source_report", type=Path)
    p.add_argument("--out", type=Path)
    a = p.parse_args()
    expect(a.user_owned_source_report.is_file(),
           "input report must be a local existing file")
    expect(a.user_owned_source_report.stat().st_size <= MAX_REPORT_BYTES,
           "source report exceeds bounded JSON limit")
    data = json.loads(a.user_owned_source_report.read_text(encoding="utf-8"))
    result = evaluate(mapping(data, "report"))
    serialized = json.dumps(result, indent=2, sort_keys=True,
                            ensure_ascii=False) + "\n"
    if a.out:
        a.out.write_text(serialized, encoding="utf-8")
    else:
        print(serialized, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
